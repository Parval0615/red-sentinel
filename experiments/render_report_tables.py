from __future__ import annotations

import argparse
import html
import json
import math
from pathlib import Path
from typing import Any, Iterable, Sequence


DEFAULT_FIGURE_NAMES = {
    "asr_comparison": "asr_before_after.svg",
    "attack_radar": "attack_category_radar.svg",
}


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Render ASR before/after experiment results as Markdown tables.")
    parser.add_argument("--input", required=True, type=Path, help="Path to asr_before_after.json.")
    parser.add_argument("--output", type=Path, help="Optional Markdown output path. Defaults to stdout.")
    parser.add_argument(
        "--figures-dir",
        type=Path,
        help="Optional directory where reproducible SVG figures are written.",
    )
    args = parser.parse_args(argv)

    payload = load_result(args.input)
    markdown = render_markdown_tables(payload)

    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(markdown, encoding="utf-8")
    else:
        print(markdown, end="")

    if args.figures_dir:
        write_svg_figures(payload, args.figures_dir)
    return 0


def load_result(path: Path) -> dict[str, Any]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise ValueError(f"ASR result must be a JSON object: {path}")
    if not isinstance(payload.get("scenario_results"), list):
        raise ValueError(f"Missing scenario_results list in ASR result: {path}")
    if not isinstance(payload.get("summary"), dict):
        raise ValueError(f"Missing summary object in ASR result: {path}")
    return payload


def render_markdown_tables(payload: dict[str, Any]) -> str:
    lines = [
        "<!-- generated by experiments/render_report_tables.py -->",
        "",
        "# ASR Before/After Experiment Tables",
        "",
        f"- schema_version: `{payload.get('schema_version', 'unknown')}`",
        f"- generated_at: `{payload.get('generated_at', 'unknown')}`",
        "",
        "## Scenario Results",
        "",
        "| scenario | cases_total | asr_no_defense | asr_with_defense | delta | fpr | blocked | asked |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]

    for result in _scenario_results(payload):
        lines.append(_table_row(result))

    lines.extend(
        [
            "",
            "## Summary",
            "",
            "| scope | cases_total | asr_no_defense | asr_with_defense | delta | fpr | blocked | asked |",
            "|---|---:|---:|---:|---:|---:|---:|---:|",
            _table_row(payload["summary"], label="summary"),
            "",
            "## FPR Distribution",
            "",
            "| scope | benign_cases_total | false_positives | fpr | benign_allow | benign_deny | benign_ask |",
            "|---|---:|---:|---:|---:|---:|---:|",
            *[
                _fpr_distribution_row(result, label=str(result.get("scenario", "unknown")))
                for result in _scenario_results(payload)
            ],
            _fpr_distribution_row(payload["summary"], label="summary"),
            "",
            "## Asked/Decision Distribution",
            "",
            "| scope | cases_total | allow | deny | ask | blocked | asked | asr_with_defense |",
            "|---|---:|---:|---:|---:|---:|---:|---:|",
            *[
                _decision_distribution_row(result, label=str(result.get("scenario", "unknown")))
                for result in _scenario_results(payload)
            ],
            _decision_distribution_row(payload["summary"], label="summary"),
            "",
        ]
    )
    return "\n".join(lines)


def write_svg_figures(payload: dict[str, Any], figures_dir: Path) -> dict[str, Path]:
    figures_dir.mkdir(parents=True, exist_ok=True)
    asr_path = figures_dir / DEFAULT_FIGURE_NAMES["asr_comparison"]
    radar_path = figures_dir / DEFAULT_FIGURE_NAMES["attack_radar"]
    asr_path.write_text(render_asr_comparison_svg(payload), encoding="utf-8")
    radar_path.write_text(render_attack_radar_svg(payload), encoding="utf-8")
    return {"asr_comparison": asr_path, "attack_radar": radar_path}


def render_asr_comparison_svg(payload: dict[str, Any]) -> str:
    results = _scenario_results(payload)
    width = 1120
    height = 560
    margin_left = 88
    margin_right = 32
    margin_top = 78
    margin_bottom = 134
    plot_width = width - margin_left - margin_right
    plot_height = height - margin_top - margin_bottom
    group_width = plot_width / max(len(results), 1)
    bar_width = min(30, group_width * 0.26)
    baseline_color = "#8B3A3A"
    guarded_color = "#2F6F73"
    grid_color = "#D8D1C7"
    text_color = "#1F2933"

    parts = [
        _svg_header(width, height),
        f'<rect width="{width}" height="{height}" fill="#F8F5EF"/>',
        f'<text x="{margin_left}" y="38" font-size="22" font-weight="700" fill="{text_color}">'
        "ASR Before/After Defense</text>",
        f'<text x="{margin_left}" y="62" font-size="13" fill="#5D6673">'
        "Rates are rendered from asr_before_after.json; lower guarded ASR is better.</text>",
    ]

    for tick in range(0, 6):
        value = tick / 5
        y = margin_top + plot_height * (1 - value)
        parts.append(f'<line x1="{margin_left}" y1="{y:.2f}" x2="{width - margin_right}" y2="{y:.2f}" stroke="{grid_color}"/>')
        parts.append(
            f'<text x="{margin_left - 14}" y="{y + 4:.2f}" font-size="12" text-anchor="end" fill="#5D6673">'
            f"{value:.0%}</text>"
        )

    parts.append(
        f'<line x1="{margin_left}" y1="{margin_top + plot_height}" '
        f'x2="{width - margin_right}" y2="{margin_top + plot_height}" stroke="#9A9288"/>'
    )
    parts.append(f'<line x1="{margin_left}" y1="{margin_top}" x2="{margin_left}" y2="{margin_top + plot_height}" stroke="#9A9288"/>')

    for index, result in enumerate(results):
        center_x = margin_left + group_width * index + group_width / 2
        baseline = _number(result.get("asr_no_defense"))
        guarded = _number(result.get("asr_with_defense"))
        for offset, value, color, label in (
            (-bar_width * 0.65, baseline, baseline_color, "no defense"),
            (bar_width * 0.65, guarded, guarded_color, "with defense"),
        ):
            bar_height = plot_height * value
            x = center_x + offset - bar_width / 2
            y = margin_top + plot_height - bar_height
            parts.append(
                f'<rect x="{x:.2f}" y="{y:.2f}" width="{bar_width:.2f}" height="{bar_height:.2f}" '
                f'rx="3" fill="{color}"><title>{_escape(result["scenario"])} {label}: {value:.1%}</title></rect>'
            )
            parts.append(
                f'<text x="{x + bar_width / 2:.2f}" y="{max(y - 6, margin_top - 8):.2f}" '
                f'font-size="11" text-anchor="middle" fill="{text_color}">{value:.0%}</text>'
            )
        parts.append(
            f'<text x="{center_x:.2f}" y="{height - margin_bottom + 30}" font-size="11" text-anchor="middle" '
            f'fill="{text_color}" transform="rotate(-35 {center_x:.2f},{height - margin_bottom + 30})">'
            f"{_escape(_short_label(result['scenario']))}</text>"
        )

    parts.extend(
        [
            _legend_item(838, 34, baseline_color, "No defense ASR"),
            _legend_item(838, 58, guarded_color, "With defense ASR"),
            "</svg>",
        ]
    )
    return "\n".join(parts)


def render_attack_radar_svg(payload: dict[str, Any]) -> str:
    results = _scenario_results(payload)
    width = 720
    height = 720
    center_x = width / 2
    center_y = height / 2 + 18
    radius = 238
    baseline_color = "#8B3A3A"
    guarded_color = "#2F6F73"
    text_color = "#1F2933"

    baseline_points = _radar_points(results, "asr_no_defense", center_x, center_y, radius)
    guarded_points = _radar_points(results, "asr_with_defense", center_x, center_y, radius)
    parts = [
        _svg_header(width, height),
        f'<rect width="{width}" height="{height}" fill="#F8F5EF"/>',
        f'<text x="48" y="42" font-size="22" font-weight="700" fill="{text_color}">Attack Category ASR Radar</text>',
        '<text x="48" y="66" font-size="13" fill="#5D6673">Each spoke is one attack category from the experiment JSON.</text>',
    ]

    for ring in range(1, 6):
        r = radius * ring / 5
        points = _regular_polygon_points(len(results), center_x, center_y, r)
        parts.append(f'<polygon points="{points}" fill="none" stroke="#D8D1C7" stroke-width="1"/>')
        parts.append(
            f'<text x="{center_x + 6:.2f}" y="{center_y - r + 4:.2f}" font-size="11" fill="#7A7168">{ring * 20}%</text>'
        )

    for index, result in enumerate(results):
        angle = _radar_angle(index, len(results))
        end_x = center_x + math.cos(angle) * radius
        end_y = center_y + math.sin(angle) * radius
        label_x = center_x + math.cos(angle) * (radius + 58)
        label_y = center_y + math.sin(angle) * (radius + 42)
        anchor = "middle"
        if label_x < center_x - 20:
            anchor = "end"
        elif label_x > center_x + 20:
            anchor = "start"
        parts.append(f'<line x1="{center_x:.2f}" y1="{center_y:.2f}" x2="{end_x:.2f}" y2="{end_y:.2f}" stroke="#C7BFB4"/>')
        parts.append(
            f'<text x="{label_x:.2f}" y="{label_y:.2f}" font-size="12" text-anchor="{anchor}" fill="{text_color}">'
            f"{_escape(_short_label(result['scenario']))}</text>"
        )

    parts.extend(
        [
            f'<polygon points="{baseline_points}" fill="{baseline_color}" fill-opacity="0.20" stroke="{baseline_color}" stroke-width="3"/>',
            f'<polygon points="{guarded_points}" fill="{guarded_color}" fill-opacity="0.22" stroke="{guarded_color}" stroke-width="3"/>',
            f'<circle cx="{center_x:.2f}" cy="{center_y:.2f}" r="3" fill="{text_color}"/>',
            _legend_item(478, 34, baseline_color, "No defense ASR"),
            _legend_item(478, 58, guarded_color, "With defense ASR"),
            "</svg>",
        ]
    )
    return "\n".join(parts)


def _scenario_results(payload: dict[str, Any]) -> list[dict[str, Any]]:
    return [item for item in payload.get("scenario_results", []) if isinstance(item, dict)]


def _table_row(result: dict[str, Any], *, label: str | None = None) -> str:
    scenario = label or str(result.get("scenario", "unknown"))
    no_defense = _number(result.get("asr_no_defense"))
    guarded = _number(result.get("asr_with_defense"))
    delta = no_defense - guarded
    return (
        f"| `{scenario}` | {int(result.get('cases_total', 0))} | {_format_rate(no_defense)} | "
        f"{_format_rate(guarded)} | {_format_rate(delta)} | {_format_rate(_number(result.get('fpr')))} | "
        f"{int(result.get('blocked', 0))} | {int(result.get('asked', 0))} |"
    )


def _fpr_distribution_row(result: dict[str, Any], *, label: str) -> str:
    return (
        f"| `{label}` | {_integer(result.get('benign_cases_total'))} | "
        f"{_integer(result.get('false_positives'))} | {_format_rate(_number(result.get('fpr')))} | "
        f"{_distribution_count(result, 'benign_decision_distribution', 'allow')} | "
        f"{_distribution_count(result, 'benign_decision_distribution', 'deny')} | "
        f"{_distribution_count(result, 'benign_decision_distribution', 'ask')} |"
    )


def _decision_distribution_row(result: dict[str, Any], *, label: str) -> str:
    return (
        f"| `{label}` | {_integer(result.get('cases_total'))} | "
        f"{_distribution_count(result, 'decision_distribution', 'allow')} | "
        f"{_distribution_count(result, 'decision_distribution', 'deny')} | "
        f"{_distribution_count(result, 'decision_distribution', 'ask')} | "
        f"{_integer(result.get('blocked'))} | {_integer(result.get('asked'))} | "
        f"{_format_rate(_number(result.get('asr_with_defense')))} |"
    )


def _format_rate(value: float) -> str:
    return f"{value * 100:.1f}%"


def _number(value: Any) -> float:
    if isinstance(value, int | float):
        return float(value)
    return 0.0


def _integer(value: Any) -> int:
    if isinstance(value, int | float):
        return int(value)
    return 0


def _distribution_count(result: dict[str, Any], key: str, decision: str) -> int:
    distribution = result.get(key)
    if not isinstance(distribution, dict):
        return 0
    return _integer(distribution.get(decision))


def _svg_header(width: int, height: int) -> str:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" role="img">'
    )


def _legend_item(x: int, y: int, color: str, label: str) -> str:
    return (
        f'<g><rect x="{x}" y="{y - 11}" width="16" height="16" rx="3" fill="{color}"/>'
        f'<text x="{x + 24}" y="{y + 1}" font-size="13" fill="#1F2933">{_escape(label)}</text></g>'
    )


def _radar_points(results: list[dict[str, Any]], metric: str, center_x: float, center_y: float, radius: float) -> str:
    points = []
    for index, result in enumerate(results):
        value = max(0.0, min(1.0, _number(result.get(metric))))
        angle = _radar_angle(index, len(results))
        points.append(f"{center_x + math.cos(angle) * radius * value:.2f},{center_y + math.sin(angle) * radius * value:.2f}")
    return " ".join(points)


def _regular_polygon_points(count: int, center_x: float, center_y: float, radius: float) -> str:
    points = []
    for index in range(count):
        angle = _radar_angle(index, count)
        points.append(f"{center_x + math.cos(angle) * radius:.2f},{center_y + math.sin(angle) * radius:.2f}")
    return " ".join(points)


def _radar_angle(index: int, count: int) -> float:
    return -math.pi / 2 + 2 * math.pi * index / max(count, 1)


def _short_label(value: str) -> str:
    replacements = {
        "environment_awareness_pollution": "env awareness",
        "training_data_leakage": "data leakage",
        "prompt_injection": "prompt injection",
        "tool_tampering": "tool tampering",
        "memory_poisoning": "memory poisoning",
        "goal_drift": "goal drift",
        "jailbreak": "jailbreak",
    }
    return replacements.get(value, value.replace("_", " "))


def _escape(value: str) -> str:
    return html.escape(value, quote=True)


def _scenario_names(results: Iterable[dict[str, Any]]) -> list[str]:
    return [str(result.get("scenario", "unknown")) for result in results]


if __name__ == "__main__":
    raise SystemExit(main())
